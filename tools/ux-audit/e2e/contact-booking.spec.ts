import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const prefix=process.env.E2E_PREFIX||'';
for(const width of [390,1440]) for(const lang of ['en','fr']) test(`contact booking ${width} ${lang}`,async({page},info)=>{
  await page.setViewportSize({width,height:950});
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.addInitScript(language=>localStorage.setItem('cv-theme',language==='fr'?'dark':'light'),lang);
  let bookings=0;
  await page.route('https://cal.com/**',route=>{ bookings++; return route.fulfill({contentType:'text/html',body:'<!doctype html><html><body><h1>Booking calendar preview</h1></body></html>'}); });
  await page.goto(`${prefix}/index-${lang}.html`);
  expect(bookings).toBe(0);
  await expect(page.locator('.cv-nav-links')).toHaveCSS('border-top-left-radius','12px');
  expect(await page.locator('.cv-nav-lang').evaluate(e=>parseFloat(getComputedStyle(e).borderTopLeftRadius))).toBeLessThanOrEqual(12);
  const trigger=page.locator('.contact-cta-lead');
  await trigger.click();
  const dialog=page.locator('#cv-booking-dialog');
  await expect(dialog).toBeVisible();
  await expect(page.locator('.cv-booking-close')).toBeFocused();
  await expect(page.locator('.cv-booking-frame')).toHaveAttribute('src',/cal\.com\/antoine-boucher-dev\/30min\?embed=true/);
  expect(await page.locator('.cv-booking-confetti span').count()).toBeGreaterThan(0);
  await expect(page.locator('.cv-booking-loading')).toBeHidden();
  const bounds=await dialog.boundingBox();
  expect(bounds!.width).toBeLessThanOrEqual(width);
  await page.screenshot({path:info.outputPath('booking-modal.png')});
  await page.keyboard.press('Escape');
  await expect(dialog).toBeHidden();
  await expect(trigger).toBeFocused();
  await expect(page.locator('.cv-booking-frame')).not.toHaveAttribute('src');
  await expect(page.locator('.cv-booking-confetti span')).toHaveCount(0);
  await page.locator('.call-cta-btn').click();
  await expect(dialog).toBeVisible();
  await page.locator('.cv-booking-close').click();
  await expect(dialog).toBeHidden();
});
for(const preference of ['reduce','paused'] as const) test(`booking respects ${preference}`,async({page})=>{
  await page.emulateMedia({reducedMotion:preference==='reduce'?'reduce':'no-preference'});
  if(preference==='paused') await page.addInitScript(()=>localStorage.setItem('cv-motion-paused','true'));
  await page.route('https://cal.com/**',route=>route.abort());
  await page.goto(`${prefix}/index-en.html`);
  await page.locator('.call-cta-btn').click();
  await expect(page.locator('#cv-booking-dialog')).toBeVisible();
  await expect(page.locator('.cv-booking-confetti span')).toHaveCount(0);
  await expect(page.locator('.cv-booking-footer a[target="_blank"]')).toHaveAttribute('href','https://cal.com/antoine-boucher-dev/30min');
});
test('booking dialog accessibility',async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.route('https://cal.com/**',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><html lang="en"><head><title>Calendar</title></head><body><main><h1>Booking calendar</h1></main></body></html>'}));
  await page.goto(`${prefix}/index-en.html`);
  await page.locator('.call-cta-btn').click();
  const audit=await new AxeBuilder({page}).include('#cv-booking-dialog').withTags(['wcag2a','wcag2aa']).analyze();
  expect(audit.violations).toEqual([]);
});
