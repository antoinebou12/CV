test('pausing finishes disclosures and preserves filter state',async({page})=>{
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.goto(`${prefix}/index-en.html`);
  const job=page.locator('details.cv-job').first();
  await job.evaluate((node:HTMLDetailsElement)=>node.open=false);
  await job.locator(':scope > summary').click({force:true});
  await page.evaluate(()=>document.documentElement.dataset.motion='paused');
  await expect(job).toHaveAttribute('open','');
  await expect(job).not.toHaveAttribute('data-motion-target');
  await expect.poll(()=>job.evaluate(node=>node.style.height)).toBe('');
  await page.locator('.expertise-domain').nth(1).click();
  await expect(page.locator('.expertise-domain').nth(1)).toHaveAttribute('aria-selected','true');
  expect(await page.locator('.cv-skill-indicator').evaluate(node=>node.getAnimations().filter(a=>a.playState==='running').length)).toBe(0);
});
