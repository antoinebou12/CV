import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const prefix=process.env.E2E_PREFIX||'';
for(const lang of ['en','fr']) test(`CV interaction polish ${lang}`,async({page,context},info)=>{
  await context.grantPermissions(['clipboard-read','clipboard-write']);
  await page.setViewportSize({width:1440,height:1000});
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.addInitScript(language=>localStorage.setItem('cv-theme',language==='fr'?'dark':'light'),lang);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${prefix}/index-${lang}.html`);
  const domains=page.locator('.expertise-domain');
  await domains.nth(1).click();
  await expect(domains.nth(1)).toHaveAttribute('aria-selected','true');
  await expect.poll(()=>page.evaluate(()=>{const a=document.querySelector('.cv-skill-indicator').getBoundingClientRect();const b=document.querySelector('.expertise-domain[aria-selected="true"]').getBoundingClientRect();return Math.abs(a.left-b.left)+Math.abs(a.top-b.top)+Math.abs(a.width-b.width);})).toBeLessThan(2);
  await domains.first().click();
  await page.locator('[data-expertise-search]').fill('Python');
  await expect(page.locator('.expertise-panel:visible .expertise-pill:visible')).toHaveCount(1);
  await expect(page.locator('.expertise-panel:visible .expertise-pill:visible')).toHaveAttribute('data-skill','Python');
  await page.locator('[data-expertise-search]').fill('');
  const job=page.locator('details.cv-job').first();
  await job.locator(':scope > summary').click();
  await expect(job).toHaveAttribute('open','');
  await expect(job).not.toHaveAttribute('data-motion-target');
  await job.locator(':scope > summary').click();
  await expect(job).not.toHaveAttribute('open');
  await job.locator(':scope > summary').focus();
  await page.keyboard.press('Enter');
  await expect(job).toHaveAttribute('open','');
  await expect(job).not.toHaveAttribute('data-motion-target');
  const email=page.locator('.contact-item a[href^="mailto:"]').first();
  await page.locator('.cv-copy-email').first().click();
  await expect(page.locator('.cv-copy-feedback')).toContainText(lang==='fr'?'copiée':'copied');
  expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe((await email.getAttribute('href'))!.slice(7));
  await page.locator('.cv-nav-section[href="#projects"]').click();
  await expect(page.locator('.cv-nav-section[href="#projects"]')).toHaveAttribute('aria-current','location');
  await page.locator('#projects').evaluate((e:HTMLDetailsElement)=>e.open=true);
  const card=page.locator('.project-card').first();
  const title=await card.locator('.project-title a').first().textContent();
  const preview=card.locator('.cv-project-preview-trigger');
  await preview.evaluate(node=>{for(let parent=node.parentElement;parent;parent=parent.parentElement)if(parent.tagName==='DETAILS')(parent as HTMLDetailsElement).open=true;});
  await preview.click();
  await expect(page.locator('#cv-project-preview')).toBeVisible();
  await expect(page.locator('#cv-project-preview-title')).toHaveText(title!.trim());
  await expect(page.locator('.cv-project-preview-links a').first()).toHaveAttribute('href',await card.locator('.project-title a').first().getAttribute('href'));
  expect(await page.locator('.cv-project-preview-body').textContent()).toContain((await card.locator('.project-impact').first().textContent())!.trim());
  const audit=await new AxeBuilder({page}).include('#cv-project-preview').withTags(['wcag2a','wcag2aa']).analyze();
  expect(audit.violations).toEqual([]);
  await page.screenshot({path:info.outputPath('project-preview.png')});
  await page.keyboard.press('Escape');
  await expect(page.locator('#cv-project-preview')).toBeHidden();
  await expect(preview).toBeFocused();
  expect(errors).toEqual([]);
});
