#!/usr/bin/env python3
"""Download the site's web fonts (Fraunces, Open Sans) as self-hosted WOFF2 files.

Google Fonts serves a variable WOFF2 per script subset. Self-hosting removes a
render-blocking third-party request on the CV and the blog and lets both pages
preload the two faces the first paint needs. Run once when fonts change:

    python scripts/build/fetch_fonts.py

Writes css/fonts/*.woff2 and css/fonts/fonts.css (used by the static CV).
hugo/assets/fonts.css mirrors the same @font-face rules for the blog.
"""
from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "css" / "fonts"
CSS_URL = ("https://fonts.googleapis.com/css2?family=Fraunces:wght@500..600"
           "&family=Open+Sans:wght@400..800&display=swap")
# A modern UA makes Google return variable WOFF2 sources with unicode-range splits.
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
KEEP = {"latin", "latin-ext"}
SLUG = {"Fraunces": "fraunces", "Open Sans": "open-sans"}


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def main() -> int:
    css = fetch(CSS_URL).decode("utf-8")
    blocks = re.findall(r"/\* (\w[\w-]*) \*/\s*@font-face \{(.*?)\}", css, re.S)
    rules = []
    for subset, body in blocks:
        if subset not in KEEP:
            continue
        family = re.search(r"font-family: '([^']+)'", body).group(1)
        weight = re.search(r"font-weight: ([\d ]+);", body).group(1)
        src = re.search(r"url\((https://[^)]+\.woff2)\)", body).group(1)
        unicode_range = re.search(r"unicode-range: ([^;]+);", body).group(1)
        name = f"{SLUG[family]}-{subset}.woff2"
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / name).write_bytes(fetch(src))
        rules.append((family, weight, name, unicode_range, subset))
        print(f"{name}: {(OUT / name).stat().st_size} bytes")
    lines = ["/* Generated by scripts/build/fetch_fonts.py from Google Fonts (OFL licensed families). */"]
    for family, weight, name, unicode_range, subset in rules:
        lines.append(
            "@font-face { font-family: '%s'; font-style: normal; font-weight: %s; font-display: swap; "
            "src: url('%s') format('woff2'); unicode-range: %s; }" % (family, weight, name, unicode_range))
    (OUT / "fonts.css").write_text("\n".join(lines) + "\n", encoding="utf-8")
    hugo_css = (ROOT / "hugo" / "assets" / "fonts.css")
    hugo_lines = ["{{- /* Generated by scripts/build/fetch_fonts.py; executed as a template so font URLs follow baseURL. */ -}}"]
    for family, weight, name, unicode_range, subset in rules:
        hugo_lines.append(
            "@font-face { font-family: '%s'; font-style: normal; font-weight: %s; font-display: swap; "
            "src: url('{{ \"fonts/%s\" | relURL }}') format('woff2'); unicode-range: %s; }" % (family, weight, name, unicode_range))
    hugo_css.write_text("\n".join(hugo_lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT / 'fonts.css'} and {hugo_css}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
